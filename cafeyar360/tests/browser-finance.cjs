const fs=require('node:fs');
const {chromium}=require('playwright');
fs.mkdirSync('test-artifacts',{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
 const ctx=await browser.newContext();const page=await ctx.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8010/cashier');await page.waitForSelector('#login-dialog[open]');
 await page.locator('[data-login="admin"]').click();await page.locator('#login-form button[type=submit]').click();
 await page.waitForSelector('[data-action="payment-correction"]');
 const orderRes=await ctx.request.post('http://127.0.0.1:8010/api/orders',{data:{items:[{product_id:2,qty:1}],fulfillment:'takeaway',payment_method:'cash',idempotency_key:'browser-finance-'+Date.now()}});
 if(orderRes.status()!==201)throw Error('create order failed');const order=await orderRes.json();
 await ctx.request.post(`http://127.0.0.1:8010/api/orders/${order.id}/pay`,{data:{method:'cash'}});
 let receipt=await (await ctx.request.get(`http://127.0.0.1:8010/api/orders/${order.id}/receipt`)).json();
 await page.reload();await page.waitForSelector(`[data-oid="${order.id}"]`);
 page.on('dialog',async d=>{
  if(d.message().startsWith('روش درست'))await d.accept('pos');
  else if(d.message().startsWith('شماره پیگیری'))await d.accept('BROWSER-REVISION');
  else if(d.message().startsWith('دلیل اصلاح'))await d.accept('اصلاح آزمایشی مرورگر');
  else if(d.message().startsWith('مبلغ واقعی'))await d.accept(String(order.total-1000));
  else if(d.message().startsWith('شرح مغایرت'))await d.accept('کسری آزمایشی مرورگر');
  else if(d.message().startsWith('نتیجه بررسی'))await d.accept('بررسی آزمایشی انجام شد');
  else await d.dismiss();
 });
 const correction=page.waitForResponse(r=>r.url().endsWith('/correction')&&r.request().method()==='PATCH');
 await page.locator(`[data-oid="${order.id}"]`).click();if((await correction).status()!==200)throw Error('correction failed');
 await page.waitForSelector(`[data-pid="${receipt.payment.id}"]`);
 const issue=page.waitForResponse(r=>r.url().endsWith('/discrepancies')&&r.request().method()==='POST');
 await page.locator(`[data-pid="${receipt.payment.id}"]`).click();if((await issue).status()!==201)throw Error('discrepancy failed');
 await page.waitForSelector('[data-action="resolve-discrepancy"]');
 const resolve=page.waitForResponse(r=>r.url().endsWith('/resolve')&&r.request().method()==='PATCH');
 await page.locator('[data-action="resolve-discrepancy"]').first().click();if((await resolve).status()!==200)throw Error('resolve failed');
 await page.getByText('نتیجه: بررسی آزمایشی انجام شد',{exact:false}).first().waitFor();
 await page.screenshot({path:'test-artifacts/sprint2-cashier.png',fullPage:true});
 const row=page.locator(`[data-oid="${order.id}"]`).locator('xpath=ancestor::tr');
 const popup=page.waitForEvent('popup');await row.getByRole('link',{name:'رسید',exact:true}).click();const printPage=await popup;
 await printPage.waitForSelector('#print-receipt');
 if(!(await printPage.locator('body').innerText()).includes('BROWSER-REVISION'))throw Error('receipt did not update');
 await printPage.screenshot({path:'test-artifacts/sprint2-receipt.png',fullPage:true});
 await printPage.emulateMedia({media:'print'});if(await printPage.locator('#print-receipt').isVisible())throw Error('print button must be hidden');
 await printPage.pdf({path:'test-artifacts/sprint2-receipt.pdf',format:'A5'});
 await page.goto('http://127.0.0.1:8010/finance');await page.waitForSelector('[data-form="report-period"]');
 await page.locator('input[name="start"]').fill('2020-01-01');await page.locator('input[name="end"]').fill('2099-12-31');
 const filtered=page.waitForResponse(r=>r.url().includes('/api/finance?start=2020-01-01'));
 await page.locator('[data-form="report-period"] button').click();if((await filtered).status()!==200)throw Error('report filter failed');
 await page.getByRole('heading',{name:'فروش ماهانه تحویل‌شده'}).waitFor();
 await page.screenshot({path:'test-artifacts/sprint2-finance.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('finance horizontal overflow');
 await page.goto('http://127.0.0.1:8010/analytics');await page.getByText('میانگین مبلغ سفارش',{exact:true}).waitFor();
 console.log(JSON.stringify({correction:true,discrepancyResolution:true,receiptPopup:true,printPdf:true,reportFilter:true,monthlyChart:true,mobileFinance:true,pageErrors:errors}));
 await browser.close();if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e.message);process.exit(1)});
